/**
 * Project Ascalon — Lane-aware trajectory exporter.
 *
 * Operational examples and synthetic curriculum are deliberately separate.
 * Operational admission requires an evidence manifest produced by an
 * independent receipt/review verifier; a string evidence ID alone is not proof.
 */
import { createHash } from "node:crypto";
import { AscalonTrajectoryValidator } from "../validators/AscalonTrajectoryValidator";

export type AscalonDatasetLane = "VERIFIED_OPERATIONAL" | "SYNTHETIC_CURRICULUM";
export type DatasetSplit = "train" | "validation" | "test";

export interface EvidenceAdmissionManifest {
  /** Receipt IDs independently checked against the authoritative evidence store. */
  readonly verifiedOutcomeEvidenceIds: ReadonlySet<string>;
  /** Human review references independently checked against the review ledger. */
  readonly humanReviewRefs: ReadonlySet<string>;
  /** Deterministic-teacher attestations tied to versioned rules and source evidence. */
  readonly deterministicTeacherAttestationRefs: ReadonlySet<string>;
}

export interface SplitResult {
  readonly lane: AscalonDatasetLane;
  readonly train: any[];
  readonly validation: any[];
  readonly test: any[];
  readonly rejected: Array<{ trajectory: any; reasons: string[] }>;
  readonly splitManifest: {
    readonly policyVersion: string;
    readonly assignment: string;
    readonly totalExported: number;
    readonly trainCount: number;
    readonly validationCount: number;
    readonly testCount: number;
    readonly rejectedCount: number;
    readonly familyCount: number;
    readonly trainFamilyCount: number;
    readonly validationFamilyCount: number;
    readonly testFamilyCount: number;
    readonly splitRatio: string;
  };
}

const SPLIT_POLICY_VERSION = "sha256-mission-family-70-15-15-v1";
const PRODUCTION_LABEL_SOURCES = new Set([
  "VERIFIED_OUTCOME",
  "HUMAN_EXPERT",
  "DETERMINISTIC_TEACHER",
]);
const CURRICULUM_LABEL_SOURCES = new Set([
  "SIMULATION",
  "SIMULATION_PSEUDO",
  "DETERMINISTIC_TEACHER",
]);

function familyKeyOf(trajectory: any): string | null {
  const raw =
    trajectory?.episode?.missionFamily ??
    trajectory?.episode?.caseId ??
    trajectory?.episode?.missionId;
  if (typeof raw !== "string" || raw.trim().length === 0) return null;
  return raw.trim();
}

function splitForFamily(familyKey: string): DatasetSplit {
  const digest = createHash("sha256")
    .update(SPLIT_POLICY_VERSION + ":" + familyKey, "utf8")
    .digest("hex");
  const bucket = Number.parseInt(digest.slice(0, 8), 16) % 10_000;
  if (bucket < 7_000) return "train";
  if (bucket < 8_500) return "validation";
  return "test";
}

function appendIssue(reasons: string[], code: string): void {
  if (!reasons.includes(code)) reasons.push(code);
}

export class AscalonTrajectoryExporter {
  /**
   * Production-training admission. The supplied manifest must be generated by
   * an independent verifier; this method never treats an evidence ID's
   * presence in the trajectory as proof that the referenced receipt is valid.
   */
  public static exportDataset(
    trajectories: any[],
    evidence: EvidenceAdmissionManifest,
  ): SplitResult {
    return this.exportLane(trajectories, "VERIFIED_OPERATIONAL", evidence);
  }

  /**
   * Synthetic curriculum is exportable only as its own lane. It can never be
   * returned by exportDataset and must not be concatenated with operational data.
   */
  public static exportCurriculumDataset(trajectories: any[]): SplitResult {
    return this.exportLane(trajectories, "SYNTHETIC_CURRICULUM");
  }

  private static exportLane(
    trajectories: any[],
    lane: AscalonDatasetLane,
    evidence?: EvidenceAdmissionManifest,
  ): SplitResult {
    const rejected: Array<{ trajectory: any; reasons: string[] }> = [];
    const familyGroups = new Map<string, any[]>();

    for (const trajectory of trajectories) {
      const reasons: string[] = [];
      const report = AscalonTrajectoryValidator.validate(trajectory);
      for (const issue of report.issues) appendIssue(reasons, issue.code);

      const provenance = trajectory?.provenance ?? {};
      const environmentType = trajectory?.environment?.environmentType;
      const labelSource = provenance.labelSource;
      const synthetic =
        environmentType === "SIMULATION" ||
        provenance.simulation === true ||
        provenance.synthetic === true;

      if (provenance.trainingEligible !== true) {
        appendIssue(reasons, "NOT_MARKED_TRAINING_ELIGIBLE");
      }

      if (lane === "VERIFIED_OPERATIONAL") {
        if (synthetic) appendIssue(reasons, "SYNTHETIC_NOT_ALLOWED_IN_OPERATIONAL_LANE");
        if (environmentType !== "REAL" && environmentType !== "PRODUCTION") {
          appendIssue(reasons, "OPERATIONAL_ENVIRONMENT_NOT_VERIFIED");
        }
        if (!PRODUCTION_LABEL_SOURCES.has(labelSource)) {
          appendIssue(reasons, "UNAPPROVED_OPERATIONAL_LABEL_SOURCE");
        }
        if (!evidence) {
          appendIssue(reasons, "INDEPENDENT_EVIDENCE_MANIFEST_REQUIRED");
        } else if (labelSource === "VERIFIED_OUTCOME") {
          const receiptId = trajectory?.outcome?.verificationEvidenceId;
          if (
            trajectory?.outcome?.verified !== true ||
            typeof receiptId !== "string" ||
            !evidence.verifiedOutcomeEvidenceIds.has(receiptId)
          ) {
            appendIssue(reasons, "VERIFIED_OUTCOME_RECEIPT_NOT_ATTESTED");
          }
        } else if (labelSource === "HUMAN_EXPERT") {
          const reviewRef = provenance.humanReviewRef;
          if (typeof reviewRef !== "string" || !evidence.humanReviewRefs.has(reviewRef)) {
            appendIssue(reasons, "HUMAN_REVIEW_NOT_ATTESTED");
          }
        } else if (labelSource === "DETERMINISTIC_TEACHER") {
          const teacherRef = provenance.teacherAttestationRef;
          if (
            typeof teacherRef !== "string" ||
            !evidence.deterministicTeacherAttestationRefs.has(teacherRef)
          ) {
            appendIssue(reasons, "DETERMINISTIC_TEACHER_ATTESTATION_MISSING");
          }
        }

        if (trajectory?.outcome?.status === "SUCCESS") {
          const receiptId = trajectory?.outcome?.verificationEvidenceId;
          if (
            trajectory?.outcome?.verified !== true ||
            typeof receiptId !== "string" ||
            !evidence?.verifiedOutcomeEvidenceIds.has(receiptId)
          ) {
            appendIssue(reasons, "SUCCESS_WITHOUT_INDEPENDENT_VERIFICATION");
          }
        }
        if (trajectory?.outcome?.verified === true) {
          const receiptId = trajectory?.outcome?.verificationEvidenceId;
          if (
            typeof receiptId !== "string" ||
            !evidence?.verifiedOutcomeEvidenceIds.has(receiptId)
          ) {
            appendIssue(reasons, "OUTCOME_RECEIPT_NOT_IN_EVIDENCE_MANIFEST");
          }
        }
      } else {
        if (!synthetic) appendIssue(reasons, "NON_SYNTHETIC_RECORD_IN_CURRICULUM_LANE");
        if (!CURRICULUM_LABEL_SOURCES.has(labelSource)) {
          appendIssue(reasons, "UNAPPROVED_CURRICULUM_LABEL_SOURCE");
        }
        if (labelSource === "VERIFIED_OUTCOME") {
          appendIssue(reasons, "SYNTHETIC_RECORD_CANNOT_CLAIM_VERIFIED_OUTCOME");
        }
      }

      const familyKey = familyKeyOf(trajectory);
      if (!familyKey) appendIssue(reasons, "MISSING_MISSION_FAMILY_KEY");

      if (reasons.length > 0) {
        rejected.push({ trajectory, reasons });
        continue;
      }

      const key = familyKey as string;
      const group = familyGroups.get(key) ?? [];
      group.push(trajectory);
      familyGroups.set(key, group);
    }

    const train: any[] = [];
    const validation: any[] = [];
    const test: any[] = [];
    let trainFamilyCount = 0;
    let validationFamilyCount = 0;
    let testFamilyCount = 0;

    for (const [familyKey, items] of familyGroups.entries()) {
      const split = splitForFamily(familyKey);
      if (split === "train") {
        train.push(...items);
        trainFamilyCount += 1;
      } else if (split === "validation") {
        validation.push(...items);
        validationFamilyCount += 1;
      } else {
        test.push(...items);
        testFamilyCount += 1;
      }
    }

    return {
      lane,
      train,
      validation,
      test,
      rejected,
      splitManifest: {
        policyVersion: SPLIT_POLICY_VERSION,
        assignment: "SHA-256 hash of missionFamily, caseId, or missionId; stable across reruns",
        totalExported: train.length + validation.length + test.length,
        trainCount: train.length,
        validationCount: validation.length,
        testCount: test.length,
        rejectedCount: rejected.length,
        familyCount: familyGroups.size,
        trainFamilyCount,
        validationFamilyCount,
        testFamilyCount,
        splitRatio: "70/15/15 target bands by family hash (actual counts are data-dependent)",
      },
    };
  }

  public static toJSONL(items: any[]): string {
    return items.map((item) => JSON.stringify(item)).join("\n");
  }
}
